namespace DisplayNodes.Core
{
	/// <summary>
	/// Выравнивание виджета внутри слота
	/// </summary>
	public enum Alignment
	{
		/// <summary>
		/// Прижать к началу слота
		/// </summary>
		Start,

		/// <summary>
		/// Выровнять по центру
		/// </summary>
		Center,

		/// <summary>
		/// Прижать к концу слота
		/// </summary>
		End,

		/// <summary>
		/// Растянуть
		/// </summary>
		Stretch,
	}
}
